// For Loop
// Create a for loop to display the numbers 1 through 10.
// Initialize the variable "i" to 1, if less than or equal to 10, then increment by 1.
for (let i = 1; i <= 10; i++) {
  // Checks if the number(i) is even, then displays the number(i), if true.
  if (i % 2 == 0) {
    console.log(i);
    /*
    Output:
    2
    4
    6
    8
    10
    */
  }
}
